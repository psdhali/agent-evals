"""Pinning test for the publication-site fixtures (BUILDER1-REGENERATE-SITE-
FIXTURES-2026-08-31.md requirement 5).

The two fixtures at ``dev/site-fixtures/`` are builder 2's build target.  They
are generated by ``scripts/generate_site_fixtures.py`` feeding constructed
instance_results rows through the real ``build_run_export`` — NOT hand-authored.
So the fixture cannot disagree with the code, because the code produced it.

This test regenerates both fixtures in-memory and compares them to the
committed files.  If the exporter changes and the fixtures are not regenerated,
this test goes red — the durable fix against a hand-maintained contract.

The fixtures live OUTSIDE the repo (the sibling ``dev/`` dir, kept out of git
like the other dev/ docs), so the byte-compare only runs where that dir exists
(the owner's machine / builder 2's).  The self-consistency checks run ALWAYS
(in CI too) — they catch an exporter regression that breaks the derived
``terminated_reason`` from ``error_category`` even without the files on disk.
"""

from __future__ import annotations

import json
import pathlib
from typing import Any

import pytest

# scripts/ is a package (has __init__.py) and the repo root is on sys.path
# during tests, so the generator's row-builders are importable.
from scripts import generate_site_fixtures as gen

# <repo>/../dev/site-fixtures — same resolution the generator uses.
_FIXTURES_DIR = pathlib.Path(__file__).resolve().parents[1].parent / "site-fixtures"


def _regenerate() -> dict[str, dict[str, Any]]:
    custom, mini = gen._build_fixtures()
    return {
        "run-custom_minimal.json": custom,
        "run-mini_swe_agent-uninstrumented.json": mini,
    }


# ── self-consistency — runs everywhere (incl. CI, no fixtures on disk) ──────


def test_generated_fixtures_are_self_consistent() -> None:
    """Every instance's terminated_reason must follow from its error_category /
    verdict — the exact inconsistency the hand-authored fixtures had (same
    category, two reasons).  Runs without the on-disk files, so it pins the
    exporter's own derivation in CI too."""
    for name, data in _regenerate().items():
        for inst in data["instances"]:
            ec, tr = inst["error_category"], inst["terminated_reason"]
            if ec is None:
                # A harness that completed with a graded patch has no category.
                assert tr == "completed", (name, inst["instance_id"], ec, tr)
            else:
                expected = {
                    "HARNESS_MAX_TURNS_EXCEEDED": "max_turns_exceeded",
                    "HARNESS_STUCK": "stuck",
                    "HARNESS_TIMEOUT": "timeout",
                    "HARNESS_MAX_TOKENS_TRUNCATED": "max_tokens_truncated",
                    "HARNESS_BUDGET_EXCEEDED": "budget_exceeded",
                    "HARNESS_MODEL_REFUSED": "refused",
                    "HARNESS_CRASH": "crash",
                    "MODEL_API_ERROR": "model_api_error",
                }.get(ec)
                assert tr == expected, (name, inst["instance_id"], ec, tr)


def test_instrumented_fixture_covers_the_schema_predates_cases() -> None:
    """Builder 2 needs to see the cases that did not exist on 08-19: aborted
    (excluded), operator_infra_retry (collapsed), operator_rerun_pass_at_k
    (legitimate k), grade_invalid."""
    custom = _regenerate()["run-custom_minimal.json"]
    by_id = {i["instance_id"]: i for i in custom["instances"]}
    # Aborted pair (never dispatched) is NOT in the instances list.
    assert "scikit-learn__scikit-learn-11888" not in by_id
    # Infra-retry collapsed: django-11925 appears as its attempt-2 rerun only.
    assert "django__django-11925" in by_id
    assert by_id["django__django-11925"]["attempt"] == 2
    # Rerun_pass_at_k is a legitimate extra attempt (pass@2 present).
    assert "astropy__astropy-11962" in by_id
    assert custom["totals"]["pass_at_k"]["2"] is not None
    # grade_invalid present in integrity.
    assert custom["integrity"]["grade_invalid"] >= 1


def test_uninstrumented_fixture_keeps_the_null_rule() -> None:
    """run-mini_swe_agent-uninstrumented.json is the null-rule proof — every
    token/cost field null, and the totals are null, never 0."""
    mini = _regenerate()["run-mini_swe_agent-uninstrumented.json"]
    for inst in mini["instances"]:
        assert inst["input_tokens"] is None
        assert inst["output_tokens"] is None
        assert inst["cost_usd"] is None
    assert mini["totals"]["cost_usd_total"] is None
    assert mini["totals"]["tokens"] == {
        "input": None,
        "output": None,
        "cached": None,
        "reasoning": None,
    }
    # But it is still a real, resolvable run — the rates are measured.
    assert mini["totals"]["resolved"] >= 1


# ── byte-pin against the committed files — where they exist (local) ─────────


def test_committed_fixtures_match_the_generator() -> None:
    """The on-disk fixtures must equal the generator's output byte-for-byte
    (json.dumps indent=2, same order).  Goes red when the exporter changes and
    the fixtures are not regenerated.  Skips where the fixtures do not exist
    (CI / a checkout without the sibling dev/ dir)."""
    if not _FIXTURES_DIR.is_dir():
        pytest.skip("fixtures not present (no sibling dev/site-fixtures) — byte-pin is local-only")
    for name, data in _regenerate().items():
        path = _FIXTURES_DIR / name
        assert path.exists(), f"{name} missing — run scripts/generate_site_fixtures.py"
        assert (
            json.loads(path.read_text()) == data
        ), f"{name} is stale — run scripts/generate_site_fixtures.py to regenerate"
